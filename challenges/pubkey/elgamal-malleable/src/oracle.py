def decrypt(a, b):
    share = pow(a, X, P)
    try:
        return b * pow(share, -1, P) % P
    except ValueError:
        return None


def main():
    toks = sys.stdin.read().split()
    for i in range(0, len(toks) - 1, 2):
        try:
            a, b = int(toks[i], 16), int(toks[i + 1], 16)
        except ValueError:
            print("ERROR")
            continue
        if (a, b) == (C1, C2):
            print("REFUSED")
            continue
        mm = decrypt(a, b)
        print("ERROR" if mm is None else mm.to_bytes(64, "big").hex())


if __name__ == "__main__":
    main()
